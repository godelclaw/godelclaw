#!/usr/bin/env python3
import os
import sys
import math

try:
    import tomllib
except ModuleNotFoundError:  # Python < 3.11
    import tomli as tomllib


def expand(value, root):
    if not isinstance(value, str):
        return value
    env = dict(os.environ)
    env.setdefault("HOME", os.path.expanduser("~"))
    env.setdefault("USER", os.environ.get("USER", ""))
    env["ROOT"] = root
    env["STATE_HOME"] = os.environ.get(
        "XDG_STATE_HOME", os.path.join(env["HOME"], ".local", "state"))
    env["INSTANCE"] = os.environ.get(
        "METTACLAW_INSTANCE", os.path.basename(root))
    old = os.environ.copy()
    try:
        os.environ.clear()
        os.environ.update(env)
        return os.path.expanduser(os.path.expandvars(value))
    finally:
        os.environ.clear()
        os.environ.update(old)


def merged(defaults, local):
    """local.toml holds only what an instance changes. Every other value comes
    from default.toml, so a default changed in git reaches every instance."""
    result = dict(defaults)
    for key, value in local.items():
        if isinstance(value, dict) and isinstance(result.get(key), dict):
            result[key] = {**result[key], **value}
        else:
            result[key] = value
    return result


def shell_quote(value):
    return "'" + str(value).replace("'", "'\"'\"'") + "'"


def bool_env(value):
    return "1" if bool(value) else "0"


def emit(key, value):
    if value is None or value == "":
        return
    if isinstance(value, bool):
        value = bool_env(value)
    elif isinstance(value, list):
        value = ",".join(str(item) for item in value)
    print(f"export {key}={shell_quote(value)}")


def main():
    if len(sys.argv) != 3:
        print("usage: config_to_env.py <config.toml> <repo-root>", file=sys.stderr)
        return 2
    config_path, root = sys.argv[1], os.path.abspath(sys.argv[2])
    with open(config_path, "rb") as f:
        config = tomllib.load(f)
    defaults_path = os.path.join(root, "config", "default.toml")
    if os.path.isfile(defaults_path) and os.path.abspath(config_path) != os.path.abspath(defaults_path):
        with open(defaults_path, "rb") as f:
            config = merged(tomllib.load(f), config)

    paths = config.get("paths", {})
    agent = config.get("agent", {})
    timeout = agent.get("llm_timeout_seconds")
    if timeout is not None and (isinstance(timeout, bool)
            or not isinstance(timeout, (int, float))
            or not math.isfinite(timeout) or timeout < 1):
        print("agent.llm_timeout_seconds must be a finite number of at least one second",
              file=sys.stderr)
        return 2
    channel = config.get("channel", {})
    native_waits = {}
    for name, default in (("hard", 1800), ("connect", 30), ("first_byte", 900), ("idle", 180)):
        value = agent.get("llm_" + name + "_seconds", default)
        if (type(value) not in (int, float) or not math.isfinite(value)
                or not 0 < value <= 2147483):
            print("invalid native model wait: " + name, file=sys.stderr)
            return 2
        native_waits[name] = value
    if timeout is not None and native_waits["hard"] < timeout:
        print("native model hard deadline precedes its soft wait", file=sys.stderr)
        return 2
    native_stream = agent.get("llm_stream", True)
    if type(native_stream) is not bool:
        print("agent.llm_stream must be boolean", file=sys.stderr)
        return 2
    for name in ("recycle_bytes",):
        value = agent.get(name)
        if value is not None and (type(value) is not int or value < 0):
            print("agent.%s must be a nonnegative integer" % name, file=sys.stderr)
            return 2
    ack_delay = agent.get("input_ack_seconds", 15)
    if (isinstance(ack_delay, bool) or not isinstance(ack_delay, (int, float))
            or not math.isfinite(ack_delay) or ack_delay < 0):
        print("agent.input_ack_seconds must be a finite nonnegative number", file=sys.stderr)
        return 2
    for name in ("model_commentary", "public_tool_receipts"):
        if type(agent.get(name, False)) is not bool:
            print("agent.%s must be boolean" % name, file=sys.stderr)
            return 2
    telegram = config.get("telegram", {})
    input_policy = agent.get("input_policy", "cooperative")
    search = config.get("search", {})
    context = config.get("context", {})
    memory = config.get("memory", {})

    print("# Generated by scripts/config_to_env.py. Do not edit directly.")
    print("# Edit config/local.toml and config/secrets.env instead.")

    emit("PETTA_ROOT", expand(paths.get("petta_root"), root))
    emit("CETTA_ROOT", expand(paths.get("cetta_root"), root))
    emit("PETTA_PY_ENV", expand(paths.get("petta_py_env"), root))
    emit("SESSION_MEMORY_TOOLS", expand(paths.get("session_memory_tools"), root))
    emit("METTACLAW_CHROMA_DIR", expand(paths.get("chroma_dir"), root))
    emit("METTACLAW_TELEGRAM_OFFSET_PATH", expand(paths.get("telegram_offset_path"), root))
    emit("METTACLAW_TELEGRAM_LOG_PATH", expand(paths.get("telegram_log_path"), root))
    emit("METTACLAW_LIFECYCLE_PATH", expand(paths.get("lifecycle_path"), root))
    emit("METTACLAW_PROMPT_PATH", expand(paths.get("prompt_path"), root))
    emit("METTACLAW_HISTORY_PATH", expand(paths.get("history_path"), root))
    emit("METTACLAW_MEMORY_LOG_DIR", expand(paths.get("memory_log_dir"), root))
    emit("METTACLAW_TELEGRAM_ATTACHMENTS_DIR", expand(paths.get("attachments_dir"), root))
    emit("METTACLAW_REPOS_DIR", expand(paths.get("repos_dir"), root))
    emit("METTACLAW_PUBLIC_WORK_DIR", expand(paths.get("public_work_dir"), root))
    emit("METTACLAW_STREAM_DIR", expand(paths.get("stream_dir"), root))
    emit("METTACLAW_EMBED_MODEL", expand(paths.get("embed_model"), root))

    emit("METTACLAW_OWNER", expand(agent.get("owner"), root))
    emit("SYNTHETIC_MODEL", agent.get("synthetic_model"))
    emit("SYNTHETIC_BASE_URL", agent.get("synthetic_base_url"))
    emit("SYNTHETIC_TIMEOUT", timeout)
    for name, value in native_waits.items():
        emit("METTACLAW_LLM_" + name.upper() + "_SECONDS", value)
    emit("METTACLAW_LLM_STREAM", 1 if native_stream else 0)
    emit("METTACLAW_MODEL_COMMENTARY", agent.get("model_commentary", False))
    emit("METTACLAW_PUBLIC_TOOL_RECEIPTS", agent.get("public_tool_receipts", False))
    emit("METTACLAW_INPUT_ACK_SECONDS", ack_delay)
    emit("METTACLAW_INPUT_POLICY", input_policy)
    emit("METTACLAW_OBSERVED_STRATEGY", agent.get("observed_strategy"))
    emit("METTACLAW_SHELL_TIMEOUT_SECONDS", agent.get("shell_timeout_seconds", 120))
    emit("METTACLAW_REASONING_EFFORT", agent.get("reasoning_effort", "default"))
    emit("METTACLAW_LLM_TRANSPORT", agent.get("llm_transport"))
    emit("METTACLAW_LLM_POLICY", agent.get("llm_policy"))
    # Unset, the agent restarts at two thirds of its memory limit; 0 never.
    emit("METTACLAW_RECYCLE_BYTES", agent.get("recycle_bytes"))

    mail = config.get("mail", {})
    emit("METTACLAW_MAIL_NAME", mail.get("name"))
    emit("METTACLAW_MAIL_SOCKET", expand(mail.get("socket"), root))
    emit("METTACLAW_MAIL_SPACE", mail.get("space"))
    gateway = config.get("gateway", {})
    emit("METTACLAW_GATEWAY_AGENT", gateway.get("agent"))
    emit("METTACLAW_GATEWAY_SOCKET", expand(gateway.get("socket"), root))
    emit("METTACLAW_GATEWAY_BOOT_PROBE", gateway.get("boot_probe"))

    emit("METTACLAW_CHANNEL", channel.get("kind"))

    emit("METTACLAW_TELEGRAM_ALLOW_PRIVATE", telegram.get("allow_private"))
    # "durable": a CeTTa channel service is the bot's only poller and sender;
    # service_socket is its private client socket. Absent: the Bot API poller.
    emit("METTACLAW_TELEGRAM_TRANSPORT", telegram.get("transport"))
    emit("METTACLAW_TELEGRAM_SERVICE_SOCKET", expand(telegram.get("service_socket"), root))
    # "metta": channels/telegram.metta is the client of that service; absent
    # or "python": channels/telegram.py is.
    emit("METTACLAW_TELEGRAM_CLIENT", telegram.get("client"))
    emit("METTACLAW_TELEGRAM_POLL_LIMIT", telegram.get("poll_limit"))
    # Telegram identities and authorization sets intentionally do not pass
    # through generated .env. Keep them in mode-600 config/secrets.env, which
    # run.sh sources after .env and which is excluded from Git.

    emit("METTACLAW_SEARCH_PROVIDER", search.get("provider"))

    emit("METTACLAW_RECENT_ACTION_TURNS",
         context.get("recent_action_turns"))
    emit("METTACLAW_ANTHROPIC_CACHE_TTL",
         context.get("anthropic_cache_ttl"))
    emit("METTACLAW_CONVERSATION_EVENTS",
         context.get("conversation_events"))
    emit("METTACLAW_REPORTS_ROOT",
         expand(context.get("reports_root"), root))
    emit("METTACLAW_PROJECT_REGISTRY_PATH",
         expand(context.get("project_registry_path"), root))

    emit("METTACLAW_CHROMA_COLLECTION", memory.get("collection"))
    emit("METTACLAW_CHROMA_METRIC", memory.get("metric"))
    emit("METTACLAW_EMBED_BACKEND", memory.get("embed_backend"))
    emit("METTACLAW_EMBED_PROTOCOL", memory.get("embed_protocol"))
    emit("METTACLAW_EMBED_DIM", memory.get("embed_dim"))
    emit("METTACLAW_EMBED_DEVICE", memory.get("embed_device"))
    emit("METTACLAW_EMBED_QUERY_PROMPT_NAME", memory.get("embed_query_prompt_name"))
    emit("METTACLAW_EMBED_NORMALIZE", memory.get("embed_normalize"))
    emit("METTACLAW_EMBED_MAX_TOKENS", memory.get("embed_max_tokens"))
    emit("METTACLAW_MEMORY_SOURCE_OF_TRUTH", memory.get("source_of_truth"))
    emit("METTACLAW_MEMORY_INDEX_IS_REBUILDABLE", memory.get("index_is_rebuildable"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
