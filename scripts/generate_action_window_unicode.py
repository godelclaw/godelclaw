#!/usr/bin/env python3
"""Generate Python-compatible decimal and alphanumeric tables for CeTTa.

Run with the oracle's Python; --check verifies the checked-in table.
Whitespace classes reuse undelivered_prose_unicode. Alphanumeric additions
are measured against the supplied engine, not an assumed Unicode version.
"""
import pathlib
import os
import subprocess
import sys
import tempfile
import unicodedata

from generate_prose_unicode import char_class, metta_string

ROOT = pathlib.Path(__file__).resolve().parents[1]
TARGET = ROOT / "src/action_window_unicode.metta"


def future_alnum():
    """Measure the engine's property-table additions, not an assumed version."""
    binary = os.environ["CETTA_BIN"]
    with tempfile.TemporaryDirectory() as directory:
        source = pathlib.Path(directory) / "scalars"
        output = pathlib.Path(directory) / "alnum"
        text = "".join(chr(c) for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF)
        source.write_text(text, encoding="utf-8")
        code = ('!(import! &self (library fs)) !(import! &self (library re)) '
                '!(fs:write %s (re:replace-literal (re:compile "[^\\\\p{L}\\\\p{N}]+") '
                '(fs:read-text %s) ""))' % (metta_string(str(output)), metta_string(str(source))))
        subprocess.run([binary, "--lang", "petta", "-e", code],
                       check=True, capture_output=True, timeout=30)
        native = set(output.read_text(encoding="utf-8"))
    expected = {c for c in text if c.isalnum()}
    assert expected <= native, "native property table is older than the oracle"
    return char_class(sorted(ord(c) for c in native - expected))


def render():
    digits = [[] for _ in range(10)]
    for c in range(128, 0x110000):
        value = unicodedata.decimal(chr(c), None)
        if value is not None:
            digits[value].append("\\\\x{%X}" % c)
    rows = ['; Generated by scripts/generate_action_window_unicode.py; do not edit.',
            '; Python %d.%d, Unicode %s decimal digits.' %
            (sys.version_info.major, sys.version_info.minor, unicodedata.unidata_version),
            '(= (aw:future-alnum) %s)' % metta_string(future_alnum()),
            '(= (aw:decimal-patterns)', '   (']
    rows += ['    ("[%s]" "%d")' % ("".join(group), i)
             for i, group in enumerate(digits)]
    return "\n".join(rows) + '\n   ))\n'


def main():
    text = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print("%s is stale" % TARGET)
            return 1
    else:
        TARGET.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
