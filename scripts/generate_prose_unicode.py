#!/usr/bin/env python3
"""Write src/undelivered_prose_unicode.metta from this Python's own tables.

The native helper.undelivered_prose (src/undelivered_prose.metta) reads text
as Python's str does: str.strip/split whitespace, str.splitlines boundaries
and str.isalnum.  CeTTa's character classes are ASCII-only, so those sets are
written out here as regular-expression classes of explicit code points,
taken from the running interpreter rather than from a Unicode property
table that may be another version.  Run with the Python CeTTa embeds:

    python3 scripts/generate_prose_unicode.py          # rewrite
    python3 scripts/generate_prose_unicode.py --check  # exit 1 if stale
"""
import pathlib
import sys
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parents[1]
TARGET = ROOT / "src" / "undelivered_prose_unicode.metta"
sys.path.insert(0, str(ROOT / "src"))

ALL = range(0x110000)


def ranges(codepoints):
    out = []
    for c in codepoints:
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def escaped(c):
    return "\\x{%X}" % c


def char_class(codepoints, negated=False):
    parts = [escaped(lo) if lo == hi else escaped(lo) + "-" + escaped(hi)
             for lo, hi in ranges(codepoints)]
    return "[" + ("^" if negated else "") + "".join(parts) + "]"


def tables():
    import helper
    space = [c for c in ALL if chr(c).isspace()]
    breaks = [c for c in ALL if len(("a%sb" % chr(c)).splitlines()) == 2]
    assert set(breaks) <= set(space)
    assert "a\r\nb".splitlines() == ["a", "b"]
    blanks = [c for c in space if c not in breaks]
    alnum = [c for c in ALL if chr(c).isalnum()]
    # The affect trace ⋄⟨...⟩: an opener, then anything up to the first closer.
    pattern = helper._AFFECT_TRACE.pattern
    assert (len(pattern) == 8 and pattern[2:5] == "[^" + pattern[7]
            and pattern[5:7] == "]*"), pattern
    affect = (escaped(ord(pattern[0])) + escaped(ord(pattern[1]))
              + char_class([ord(pattern[7])], negated=True) + "*"
              + escaped(ord(pattern[7])))
    return {
        # One str.splitlines boundary: CR LF together, or one boundary character.
        "line-break": escaped(13) + escaped(10) + "|" + char_class(breaks),
        # A run of whitespace within a line.
        "blank-run": char_class(blanks) + "+",
        # A word of str.split(): a run of anything but whitespace.
        "word": char_class(space, negated=True) + "+",
        "alnum": char_class(alnum),
        "affect-trace": affect,
    }


def metta_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render():
    lines = [
        "; Generated by scripts/generate_prose_unicode.py; do not edit.",
        "; Regular expressions for the native helper.undelivered_prose, written",
        "; from Python %d.%d's str methods (Unicode %s)."
        % (sys.version_info[0], sys.version_info[1], unicodedata.unidata_version),
        "",
        '(= (prose:unicode-version) "%s")' % unicodedata.unidata_version,
    ]
    for name, pattern in tables().items():
        lines.append("(= (prose:pattern %s) %s)" % (name, metta_string(pattern)))
    return "\n".join(lines) + "\n"


def main(argv):
    text = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print("%s is stale; run %s" % (TARGET.relative_to(ROOT), sys.argv[0]))
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
