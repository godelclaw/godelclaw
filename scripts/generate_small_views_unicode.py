#!/usr/bin/env python3
"""Generate Python repr's non-printable scalar profile from a native basis."""
import sys

from generate_prose_unicode import (
    QualificationError, metta_string, native_basis, profiles, publish, ROOT,
    validate_native,
)

TARGET = ROOT / "src" / "small_views_unicode.metta"


def render(native=None):
    native = native or native_basis()
    validate_native(native)
    pattern = profiles(native)["nonprintable"]
    return ("; Generated by scripts/generate_small_views_unicode.py; do not edit.\n"
            "; Python 3.12 Unicode 15.0.0 over CeTTa Unicode %s.\n"
            "; Scalar-domain corrections; selected CeTTa source %s.\n"
            "(= (sv:nonprintable-pattern) %s)\n" %
            (native["version"], native["revision"], metta_string(pattern)))


def main():
    try:
        return publish(TARGET, render(), "--check" in sys.argv)
    except QualificationError as error:
        print("REFUSE: " + str(error), file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
