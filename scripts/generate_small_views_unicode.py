"""Python repr's non-printable scalars, from the oracle's Unicode version."""
from pathlib import Path
import sys
import unicodedata

from generate_prose_unicode import char_class, metta_string

TARGET = Path(__file__).resolve().parents[1] / "src/small_views_unicode.metta"


def render():
    pattern = char_class(c for c in range(0x110000) if not chr(c).isprintable())
    return ('; Generated by scripts/generate_small_views_unicode.py; do not edit.\n'
            '; Python %d.%d, Unicode %s str.isprintable().\n'
            '(= (sv:nonprintable-pattern) %s)\n' %
            (sys.version_info.major, sys.version_info.minor, unicodedata.unidata_version,
             metta_string(pattern)))


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if TARGET.read_text() != text:
            raise SystemExit("small view Unicode table is stale")
    else:
        TARGET.write_text(text)
